import type { Difficulty, Question, TechnologyCategory } from '../types';

type FactSeed = {
  difficulty: Difficulty;
  stem: string;
  correct: string;
  distractors: [string, string, string];
  explanation: string;
};

const buildQuestions = (
  technology: string,
  category: TechnologyCategory,
  facts: FactSeed[],
): Question[] =>
  facts.flatMap((fact, factIndex) => {
    const baseId = `${technology}-${factIndex + 1}`;
    const [misconceptionA, misconceptionB, misconceptionC] = fact.distractors;

    return [
      {
        id: `${baseId}-accurate`,
        sourceId: `${baseId}-accurate`,
        dedupeKey: `${baseId}-accurate`,
        technology,
        category,
        difficulty: fact.difficulty,
        prompt: `Which statement about ${fact.stem} is most accurate?`,
        choices: [fact.correct, misconceptionA, misconceptionB, misconceptionC],
        correctAnswer: fact.correct,
        explanation: fact.explanation,
      },
      {
        id: `${baseId}-review`,
        sourceId: `${baseId}-review`,
        dedupeKey: `${baseId}-review`,
        technology,
        category,
        difficulty: fact.difficulty,
        prompt: `Which statement about ${fact.stem} should be corrected in a technical review?`,
        choices: [misconceptionA, fact.correct, misconceptionB, misconceptionC],
        correctAnswer: misconceptionA,
        explanation: `${misconceptionA} is incorrect. ${fact.explanation}`,
      },
      {
        id: `${baseId}-red-flag`,
        sourceId: `${baseId}-red-flag`,
        dedupeKey: `${baseId}-red-flag`,
        technology,
        category,
        difficulty: fact.difficulty,
        prompt: `Which description of ${fact.stem} would be a red flag in an interview answer?`,
        choices: [misconceptionB, fact.correct, misconceptionA, misconceptionC],
        correctAnswer: misconceptionB,
        explanation: `${misconceptionB} is incorrect. ${fact.explanation}`,
      },
    ];
  });

